#!/usr/bin/env node
/**
 * Generate `cordis.patch.yml` for the codemode preset.
 *
 * The preset must mount the *complete* standard composition plus two rows —
 * the registry replaces a preset's child list wholesale and never merges future
 * changes into it — so this script slices `preset-standard`'s `plugins:` block
 * out of a composed profile tree instead of hand-copying it. Re-run after a
 * DSH upgrade to pick up additions to the standard preset:
 *
 *   node tools/gen-preset.mjs [path/to/cordis.yml]
 *
 * Default input: $DSH_HOME/profiles/desktop/cordis.yml
 */

import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PROJECT = resolve(HERE, '..');

const DSH_HOME = process.env.DSH_HOME ?? join(homedir(), '.dsh');
const INPUT = resolve(process.argv[2] ?? join(DSH_HOME, 'profiles', 'desktop', 'cordis.yml'));
const OUTPUT = join(PROJECT, 'cordis.patch.yml');

/** Rows this preset adds on top of the standard composition. */
const EXTRA_ROWS = [
  '          - id: tool-presentation',
  "            name: '@deepseek-ai/dsh-agent-tool-presentation'",
  '            config:',
  '              # Standard tools stay natively callable; run_code is added on top.',
  '              mode: both',
  '          - id: codemode',
  "            name: 'dsh-codemode'",
  '            config:',
  '              # Tool-name prefixes kept out of the request surface.',
  '              hiddenPrefixes:',
  "                - 'mcp__'",
  '              # Discovery tools, callable only from inside run_code.',
  '              metaTools:',
  '                - code_tools_list',
  '                - code_tools_search',
  '                - code_tools_describe',
];

/** Slice one top-level row's `plugins:` block, dedented to its own minimum indent. */
function slicePluginsBlock(lines, rowId) {
  const start = lines.findIndex((line) => new RegExp(`^-\\s*id:\\s*${rowId}\\s*$`).test(line));
  if (start < 0) throw new Error(`row "id: ${rowId}" not found in ${INPUT}`);
  let pluginsAt = -1;
  for (let index = start + 1; index < lines.length; index += 1) {
    if (/^-\s/.test(lines[index])) break;
    if (/^\s+plugins:\s*$/.test(lines[index])) {
      pluginsAt = index;
      break;
    }
  }
  if (pluginsAt < 0) throw new Error(`row "id: ${rowId}" has no plugins: block`);
  let end = lines.length;
  for (let index = pluginsAt + 1; index < lines.length; index += 1) {
    if (/^-\s/.test(lines[index])) {
      end = index;
      break;
    }
  }
  const block = lines.slice(pluginsAt + 1, end);
  while (block.length > 0 && block[block.length - 1].trim() === '') block.pop();
  if (block.length === 0) throw new Error(`row "id: ${rowId}" has an empty plugins: block`);
  const indent = Math.min(...block.filter((line) => line.trim() !== '').map((line) => line.match(/^\s*/)[0].length));
  return { block, indent };
}

const raw = await readFile(INPUT, 'utf8');
const lines = raw.split(/\r?\n/);
const { block, indent } = slicePluginsBlock(lines, 'preset-standard');
if (!block.some((line) => /-\s*id:\s*persona\b/.test(line))) {
  throw new Error('the sliced block does not look like the standard preset (no persona row)');
}
if (!block.some((line) => /-\s*id:\s*tool-pwsh\b/.test(line))) {
  throw new Error('the sliced block does not look like the standard preset (no tool-pwsh row)');
}

// Re-indent the block from the composed tree's 6 spaces to this patch's 10.
const shift = ' '.repeat(10 - indent);
const plugins = block.map((line) => (line.trim() === '' ? '' : shift + line));

const header = [
  '# AUTO-GENERATED by tools/gen-preset.mjs — do not edit by hand.',
  `# Source: ${INPUT}`,
  `# Generated: ${new Date().toISOString()}`,
  '#',
  "# This bundle layer inserts one row: the `codemode` agent preset. Its plugin list",
  '# mirrors the composed `preset-standard` row captured above, plus:',
  '#   - @deepseek-ai/dsh-agent-tool-presentation with mode: both  (standard tools stay',
  '#     native; run_code is added on top), and',
  '#   - this package, which masks mcp__* out of the request surface and registers the',
  '#     discovery tools that run_code programs use to find and call them.',
  '#',
  '# Re-run `node tools/gen-preset.mjs` after a DSH upgrade to re-sync the standard rows.',
];

const out = [
  ...header,
  '- insert:',
  '    - id: preset-codemode',
  "      name: '@deepseek-ai/dsh-agent-preset'",
  '      config:',
  '        id: codemode',
  '        name: "Code Mode（代码编排）"',
  '        description: "标准模式 + run_code：工具照常直接调用，MCP 工具不进上下文，由 run_code 按需发现与调用。"',
  '        order: 9',
  '        plugins:',
  ...plugins,
  ...EXTRA_ROWS,
  '',
].join('\n');

await writeFile(OUTPUT, out, 'utf8');
console.log(`wrote ${OUTPUT}`);
console.log(`  source rows: ${block.length} lines sliced from ${INPUT}`);
console.log(`  preset plugins: ${block.filter((line) => /^\s*-\s*id:/.test(line)).length} standard rows + 2 added`);
